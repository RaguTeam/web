const dictionaries: Record<Lang, Deep> = {en, ru};

export function dict(lang: Lang): Deep {
    return dictionaries[lang];
}

export function useLang(): Lang {
    return langStore.use();
}

export function useT(): Deep {
    return dictionaries[langStore.use()];
}
